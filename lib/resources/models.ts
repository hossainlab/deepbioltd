/**
 * Foundation models referenced across DeepBio's research and training work,
 * with the canonical place to get each one. `license` is left out where the
 * terms are mixed or change between releases: check the source before use.
 */

export interface ModelSource {
  name: string
  developer: string
  summary: string
  /** Title of the paper that introduced the model. */
  title: string
  authors: string
  venue: string
  year: number
  /** DOI or arXiv link for the paper. */
  paperUrl: string
  /** Canonical code or weights location. */
  codeUrl: string
  license?: string
  /** Figure from the model's own repository README; falls back to a drawn icon. */
  thumb?: string
}

